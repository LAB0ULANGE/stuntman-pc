"""Test vectors for the IOP interpreter, from the verified R5900 interpreter.

The IOP's R3000 runs MIPS I, which the EE's R5900 extends: for every MIPS I
instruction the R5900's result, cut to 32 bits, is the R3000's. emu.py is the
interpreter the lifter's verification rests on, so its results are the oracle
here. Each vector is one instruction, run on random registers and a small
memory window; the host tests (engine/host/tests/host_tests.cpp) run the same
cases on the IOP interpreter (engine/host/src/iop_vm.cpp) and compare.

    python engine/tools/iop_vectors.py          # writes engine/host/tests/iop_cpu_vectors.inc
"""

from __future__ import annotations

import os
import random
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [os.path.dirname(HERE)]

from ps2decomp import emu  # noqa: E402

OUT = os.path.join(os.path.dirname(HERE), "host", "tests", "iop_cpu_vectors.inc")
BASE = 0x00100000          # where the instruction sits (any address works for both)
DATA = BASE + 0x100        # the memory window loads and stores use
DATA_WORDS = 16
CASES_PER_OP = 40

# (name, encoder taking (rs, rt, rd, sa, imm) -> word). Registers 8-15 hold the
# operands; loads and stores use $9 as the base, pointed into the window.
SPECIAL = {"sll": 0x00, "srl": 0x02, "sra": 0x03, "sllv": 0x04, "srlv": 0x06, "srav": 0x07,
           "mfhi": 0x10, "mflo": 0x12, "mult": 0x18, "multu": 0x19, "div": 0x1A, "divu": 0x1B,
           "addu": 0x21, "subu": 0x23, "and": 0x24, "or": 0x25, "xor": 0x26, "nor": 0x27,
           "slt": 0x2A, "sltu": 0x2B}
IMMEDIATE = {"addiu": 0x09, "slti": 0x0A, "sltiu": 0x0B, "andi": 0x0C, "ori": 0x0D, "xori": 0x0E,
             "lui": 0x0F}
MEMORY = {"lb": 0x20, "lh": 0x21, "lwl": 0x22, "lw": 0x23, "lbu": 0x24, "lhu": 0x25, "lwr": 0x26,
          "sb": 0x28, "sh": 0x29, "swl": 0x2A, "sw": 0x2B, "swr": 0x2E}
ALIGN = {"lh": 2, "lhu": 2, "sh": 2, "lw": 4, "sw": 4}


def encode(name: str, rng: random.Random):
    rs, rt, rd = rng.randrange(8, 16), rng.randrange(8, 16), rng.randrange(16, 24)
    if name in SPECIAL:
        sa = rng.randrange(32)
        if name in ("mult", "multu", "div", "divu"):
            rd, sa = 0, 0
        return (rs << 21) | (rt << 16) | (rd << 11) | (sa << 6) | SPECIAL[name]
    if name in IMMEDIATE:
        return (IMMEDIATE[name] << 26) | (rs << 21) | (rd << 16) | rng.randrange(0x10000)
    # Memory: base $9, an offset keeping the access in the window and aligned.
    align = ALIGN.get(name, 1)
    offset = rng.randrange(0, DATA_WORDS * 4 - 4) // align * align
    target = rt if name.startswith("s") else rd
    return (MEMORY[name] << 26) | (9 << 21) | (target << 16) | offset


def run(word: int, regs: list, data: bytes):
    image = struct.pack("<I", word) + bytes(0x100 - 4) + data
    m = emu.Machine(BASE, image, total_size=0x1000)
    for i in range(1, 32):
        m.set(i, emu._sign32(regs[i]) & emu.MASK64 if hasattr(emu, "MASK64") else regs[i])
    m.hi = emu._sign32(regs[0]) & ((1 << 64) - 1)
    m.lo = emu._sign32(regs[0] ^ 0x5A5A5A5A) & ((1 << 64) - 1)
    m.pc = BASE
    m.step()
    out = [m.get(i) & 0xFFFFFFFF for i in range(32)]
    window = bytes(m.memory.read_int(DATA + i, 1, False) for i in range(DATA_WORDS * 4))
    return out, m.hi & 0xFFFFFFFF, m.lo & 0xFFFFFFFF, window


def main() -> int:
    rng = random.Random(0x10F)
    names = list(SPECIAL) + list(IMMEDIATE) + list(MEMORY)
    lines = ["// Generated by engine/tools/iop_vectors.py from emu.py: do not edit.",
             "// word, regs in (r0 holds the initial HI; LO = HI ^ 0x5A5A5A5A), window in,",
             "// regs out, hi, lo, window out."]
    count = 0
    for name in names:
        for _ in range(CASES_PER_OP):
            word = encode(name, rng)
            regs = [rng.getrandbits(32) for _ in range(32)]
            # Interesting values often: zero, -1, small, sign boundaries.
            for i in range(8, 16):
                if rng.random() < 0.3:
                    regs[i] = rng.choice([0, 1, 0xFFFFFFFF, 0x80000000, 0x7FFFFFFF, 31, 32])
            regs[9] = DATA
            data = bytes(rng.getrandbits(8) for _ in range(DATA_WORDS * 4))
            try:
                out, hi, lo, window = run(word, regs, data)
            except emu.EmulationError:
                continue
            words_in = ", ".join("0x%08X" % r for r in regs)
            data_in = ", ".join("0x%02X" % b for b in data)
            words_out = ", ".join("0x%08X" % r for r in out)
            data_out = ", ".join("0x%02X" % b for b in window)
            lines.append("{\"%s\", 0x%08X, {%s}, {%s}, {%s}, 0x%08X, 0x%08X, {%s}}," % (
                name, word, words_in, data_in, words_out, hi, lo, data_out))
            count += 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print("wrote %d vectors to %s" % (count, OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
